"""Write ``reports/findings.md`` from the analysis results.

The README quotes a handful of headline numbers; this file has all of them,
regenerated on every run so the two can be checked against each other.
"""

from __future__ import annotations

import json

from . import config


def _pct(x: float, d: int = 0) -> str:
    return f"{x:.{d}%}"


def _table(rows: list[tuple], header: tuple) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(r: dict) -> str:
    o, c, e, a = r["overview"], r["origin_by_country"], r["entrants_by_year"], r["entry_age"]
    w, k, g, s, ed = (r["wealth_tail"], r["concentration_over_time"], r["growth_vs_size"],
                      r["survival"], r["education"])
    gs, gf, gh = g["gibrat_survivors"], g["gibrat_with_exits_at_1B"], g["gibrat_with_exits_at_0_5B"]
    lines = [
        "# Findings",
        "",
        f"_Generated by `python -m billionaires analyze` from the snapshot of {o['snapshot']}. "
        "Do not edit by hand._",
        "",
        "## The list today",
        "",
        _table([
            ("People ever on a list in this dataset", f"{o['people_total']:,}"),
            ("On the latest list", f"{o['people_current']:,}"),
            ("Their combined wealth", f"${o['wealth_current_tn']:.1f} trillion"),
            ("Countries", o["countries_current"]),
            ("Women", _pct(o["women_share"])),
            ("Self-made / inherited and growing / inherited",
             f"{_pct(o['self_made_share'])} / {_pct(o['growing_share'])} / {_pct(o['inherited_share'])}"),
        ], ("", "")),
        "",
        "Self-made share on the historical lists (PIIE coding, not identical to Forbes'): "
        + ", ".join(f"{y}: {_pct(v)}" for y, v in o["self_made_share_by_year"].items()) + ".",
        "",
        "## Self-made share by country",
        "",
        _table([(cn, c["headcount_by_country"][cn], _pct(v))
                for cn, v in sorted(c["self_made_share_by_country"].items(), key=lambda kv: -kv[1])],
               ("Country", "Billionaires", "Self-made")),
        "",
        "## New billionaires",
        "",
        f"{e['entrants_total']:,} people entered the list between 2020 and {o['snapshot']} "
        "without having been on any earlier list.",
        "",
        _table([(y, n, _pct(e["tech_share_by_year"][y])) for y, n in e["entrants_by_year"].items()],
               ("Year", "Entrants", "From technology")),
        "",
        f"Median age at entry: **{a['entry_age_median']:.0f}**. Under 40: {_pct(a['under_40_share'])}.",
        "",
        _table([(i, f"{v:.0f}") for i, v in a["entry_age_by_industry"].items()],
               ("Industry", "Median age at entry")),
        "",
        "Youngest self-made entrants: "
        + "; ".join(f"{p['name']} ({p['age_at_first_seen']:.0f}, {p['source_of_wealth']}, "
                    f"{p['first_seen_year']:.0f})" for p in a["youngest_self_made"]) + ".",
        "",
        "## Concentration",
        "",
        f"* Pareto tail index **{w['pareto_tail_index']:.2f}** "
        f"(95% bootstrap CI {w['pareto_ci'][0]:.2f}-{w['pareto_ci'][1]:.2f}), fitted above "
        f"${w['pareto_xmin']:.1f}B on {w['pareto_n_tail']} fortunes, KS distance {w['pareto_ks']:.3f}.",
        f"* Gini coefficient among billionaires: {w['gini_within_list']:.2f}.",
        f"* Ten richest hold {_pct(w['top10_share'])} of all billionaire wealth; the top 1% hold "
        f"{_pct(w['top1pct_share'])}.",
        "",
        _table([(y, _pct(v, 1), f"${k['rank400_cutoff_bn_by_year'][y]:.1f}B")
                for y, v in k["top10_of_top400_by_year"].items()],
               ("Year", "Top 10 / top 400", "Net worth of #400")),
        "",
        "## Growth and survivorship",
        "",
        _table([
            ("Survivors only", f"{gs['slope']:+.3f}", f"{gs['se']:.3f}", f"{gs['t']:.1f}", f"{gs['n']:,}"),
            ("Exits counted at $1B", f"{gf['slope']:+.3f}", f"{gf['se']:.3f}", f"{gf['t']:.1f}", f"{gf['n']:,}"),
            ("Exits counted at $0.5B", f"{gh['slope']:+.3f}", f"{gh['se']:.3f}", f"{gh['t']:.1f}", f"{gh['n']:,}"),
        ], ("Sample", "Slope per 10x wealth", "Robust SE", "t", "Person-years")),
        "",
        f"Median year-on-year change: {g['median_annual_change']:+.1%}. "
        f"Share of person-years that end with the person off the list: {_pct(g['exit_rate_overall'], 1)}; "
        "by starting wealth: "
        + ", ".join(f"{b}: {_pct(v, 1)}" for b, v in g["exit_rate_by_wealth"].items()) + ".",
        "",
        _table([(i, f"{v:.2f}", f"{g['median_change_by_industry'][i]:+.1%}")
                for i, v in g["volatility_by_industry"].items()],
               ("Industry", "Std of annual log change", "Median change")),
        "",
        "## Survival",
        "",
        _table([(cohort, *(_pct(v) for v in path.values()))
                for cohort, path in s["survival"].items() if int(cohort) == 1996],
               ("Cohort", *map(str, s["survival"][1996].keys()))),
        "",
        "Still on the list in the latest year: "
        + ", ".join(f"{c} list {_pct(list(p.values())[-1])}" for c, p in s["survival"].items())
        + ". 1996 cohort by origin: "
        + ", ".join(f"{k_} {_pct(v)}" for k_, v in s["survival_1996_by_origin"].items()) + ".",
        "",
        "## Education",
        "",
        f"Education is recorded for {_pct(ed['education_known_share'])} of current billionaires. Among them: "
        + ", ".join(f"{k_} {_pct(v)}" for k_, v in ed["education_levels"].items()) + ". "
        f"Dropouts among self-made: {_pct(ed['dropout_share_self_made'], 1)}.",
        "",
        _table(list(ed["top_schools"].items()), ("School", "Billionaires")),
        "",
    ]
    return "\n".join(lines)


def _clean(x):
    """numpy and pandas scalars -> plain Python, recursively, for JSON."""
    if isinstance(x, dict):
        return {str(_clean(k)): _clean(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_clean(v) for v in x]
    if hasattr(x, "item"):
        x = x.item()
    if isinstance(x, float):
        return None if x != x else round(x, 6)
    return x


def write(results: dict) -> None:
    config.REPORT.parent.mkdir(parents=True, exist_ok=True)
    config.REPORT.write_text(render(results))
    (config.REPORT.parent / "results.json").write_text(json.dumps(_clean(results), indent=2) + "\n")
